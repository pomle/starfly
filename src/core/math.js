// Minimal column-major 4x4 matrix helpers (Float32Array, WebGL layout).

export const mat4 = {
  create() {
    const m = new Float32Array(16);
    m[0] = m[5] = m[10] = m[15] = 1;
    return m;
  },
  ortho(out, l, r, b, t, n, f) {
    out.fill(0);
    out[0] = 2 / (r - l);
    out[5] = 2 / (t - b);
    out[10] = -2 / (f - n);
    out[12] = -(r + l) / (r - l);
    out[13] = -(t + b) / (t - b);
    out[14] = -(f + n) / (f - n);
    out[15] = 1;
    return out;
  },
  perspective(out, fovy, aspect, near, far) {
    const f = 1 / Math.tan(fovy / 2);
    out.fill(0);
    out[0] = f / aspect;
    out[5] = f;
    out[10] = (far + near) / (near - far);
    out[11] = -1;
    out[14] = (2 * far * near) / (near - far);
    return out;
  },
  /** Translation * RotationZ * Scale for 2D-style use. */
  fromTRS2D(out, x, y, angle, sx = 1, sy = sx) {
    const c = Math.cos(angle), s = Math.sin(angle);
    out.fill(0);
    out[0] = c * sx;  out[1] = s * sx;
    out[4] = -s * sy; out[5] = c * sy;
    out[10] = 1;
    out[12] = x; out[13] = y; out[15] = 1;
    return out;
  },
  multiply(out, a, b) {
    for (let c = 0; c < 4; c++) {
      for (let r = 0; r < 4; r++) {
        out[c * 4 + r] =
          a[r] * b[c * 4] + a[4 + r] * b[c * 4 + 1] +
          a[8 + r] * b[c * 4 + 2] + a[12 + r] * b[c * 4 + 3];
      }
    }
    return out;
  },
};
