const W = 5, H = 7, GAP = 1;

/**
 * Renders text to a canvas at 1 canvas pixel per font pixel.
 * A hard drop shadow (+1,+1) is baked in for the neon-arcade look.
 */
export function makeTextCanvas(text, { color = '#ffffff', shadow = '#ff1f8e' } = {}) {
  const chars = [...text.toUpperCase()];
  const width = chars.length * (W + GAP) - GAP + 1;
  const height = H + 1;
  const canvas = document.createElement('canvas');
  canvas.width = width;
  canvas.height = height;
  const ctx = canvas.getContext('2d');
  for (const [fill, off] of [[shadow, 1], [color, 0]]) {
    ctx.fillStyle = fill;
    chars.forEach((ch, i) => {
      const rows = (GLYPHS[ch] ?? GLYPHS[' ']).split('/');
      for (let y = 0; y < H; y++) {
        for (let x = 0; x < W; x++) {
          if (rows[y][x] === '#') ctx.fillRect(i * (W + GAP) + x + off, y + off, 1, 1);
        }
      }
    });
  }
  return canvas;
}
